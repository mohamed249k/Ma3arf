function finishQuizSession() {
    // إيقاف مؤقت الاختبار الإجمالي
    clearInterval(state.runTimerInterval);
    clearInterval(state.questionTimerInterval);
    
    // حساب النسبة المئوية
    const percent = Math.round((state.correctAnswers / state.quizQuestions.length) * 100);
    
    // احتساب نقاط الخبرة المكتسبة (XP) في هذا الاختبار
    // نمنح نقاطاً تعادل الإجابات الصحيحة مضروبة بالصعوبة، مع بونص عند تحقيق نسبة ممتازة
    let xpEarned = state.score;
    if (percent === 100) {
        xpEarned += 50; // بونص إجابة كاملة
    } else if (percent >= 80) {
        xpEarned += 20; // بونص تميز
    }
    state.xpEarnedInRun = xpEarned;
    
    // تحديث بيانات الحساب وحفظها محلياً
    profile.totalQuizzes++;
    profile.totalQuestionsAnswered += state.quizQuestions.length;
    profile.totalCorrectAnswers += state.correctAnswers;
    profile.totalXp += xpEarned;
    if (percent > profile.bestScorePercent) {
        profile.bestScorePercent = percent;
    }
    
    // فحص الأوسمة والإنجازات الجديدة
    const newlyUnlocked = checkAndUnlockBadges(percent);
    
    // حفظ البيانات
    saveProfile();
    updateXpUI();
    
    // عرض شاشة النتائج وتفاصيل الأداء
    renderResultsScreen(percent, newlyUnlocked);
}

// فحص شروط الأوسمة
function checkAndUnlockBadges(runPercent) {
    const newlyUnlocked = [];
    
    // المساعد 1: باحث عن العلم (أول اختبار)
    if (!profile.unlockedBadges.includes('first_quiz') && profile.totalQuizzes >= 1) {
        unlockBadge('first_quiz', newlyUnlocked);
    }
    
    // المساعد 2: حافظ المعلومات (النتيجة الكاملة 100%)
    if (!profile.unlockedBadges.includes('perfect_score') && runPercent === 100) {
        unlockBadge('perfect_score', newlyUnlocked);
    }
    
    // المساعد 3: عالم المستقبل (مستويات متقدمة أو خبير)
    if (!profile.unlockedBadges.includes('hard_core') && state.selectedMode === 'difficulty' && (state.selectedVal === 'hard' || state.selectedVal === 'expert')) {
        unlockBadge('hard_core', newlyUnlocked);
    }
    
    // المساعد 4: سادن المعرفة (XP > 500)
    if (!profile.unlockedBadges.includes('xp_master') && profile.totalXp >= 500) {
        unlockBadge('xp_master', newlyUnlocked);
    }
    
    // المساعد 5 و 6: تتابع الإجابات الصحيحة في تصنيفات معينة
    // محب السنة (5 إجابات متتالية صحيحة في الحديث الشريف)
    if (!profile.unlockedBadges.includes('hadith_streak')) {
        let maxHadithStreak = 0;
        let tempStreak = 0;
        state.answersLog.forEach(log => {
            if (log.category === "الحديث الشريف") {
                if (log.isCorrect) {
                    tempStreak++;
                    if (tempStreak > maxHadithStreak) maxHadithStreak = tempStreak;
                } else {
                    tempStreak = 0;
                }
            }
        });
        if (maxHadithStreak >= 5) {
            unlockBadge('hadith_streak', newlyUnlocked);
        }
    }
    
    // صديق القرآن (5 إجابات متتالية صحيحة في القرآن الكريم)
    if (!profile.unlockedBadges.includes('quran_streak')) {
        let maxQuranStreak = 0;
        let tempStreak = 0;
        state.answersLog.forEach(log => {
            if (log.category === "القرآن الكريم") {
                if (log.isCorrect) {
                    tempStreak++;
                    if (tempStreak > maxQuranStreak) maxQuranStreak = tempStreak;
                } else {
                    tempStreak = 0;
                }
            }
        });
        if (maxQuranStreak >= 5) {
            unlockBadge('quran_streak', newlyUnlocked);
        }
    }
    
    return newlyUnlocked;
}

function unlockBadge(badgeId, newlyUnlockedList) {
    profile.unlockedBadges.push(badgeId);
    const badgeObj = BADGES.find(b => b.id === badgeId);
    if (badgeObj) {
        newlyUnlockedList.push(badgeObj);
        // إظهار توست الإنجاز المنبثق
        showAchievementToast(badgeObj);
    }
}

