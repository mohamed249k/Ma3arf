// حساب وعرض مستوى المستخدم الحالي وتحديث شريط الخبرة بالواجهة
function updateXpUI() {
    const xp = profile.totalXp;
    let currentLvl = LEVEL_CONFIGS[0];
    let nextLvl = LEVEL_CONFIGS[1];
    
    for (let i = 0; i < LEVEL_CONFIGS.length; i++) {
        if (xp >= LEVEL_CONFIGS[i].minXp) {
            currentLvl = LEVEL_CONFIGS[i];
            nextLvl = LEVEL_CONFIGS[i + 1] || LEVEL_CONFIGS[i];
        }
    }
    
    // حساب النسبة المئوية للوصول للمستوى التالي
    let percent = 0;
    if (currentLvl === nextLvl) {
        percent = 100; // المستوى الأقصى
    } else {
        const range = nextLvl.minXp - currentLvl.minXp;
        const currentProgress = xp - currentLvl.minXp;
        percent = Math.min(100, Math.max(0, (currentProgress / range) * 100));
    }
    
    // تحديث عناصر واجهة المستخدم بالهيدر
    document.getElementById('user-level-badge').innerText = currentLvl.icon;
    document.getElementById('current-level-name').innerText = currentLvl.name;
    document.getElementById('xp-progress-fill').style.width = `${percent}%`;
    document.getElementById('current-xp-val').innerText = xp;
    document.getElementById('next-level-xp-val').innerText = currentLvl === nextLvl ? '∞' : nextLvl.minXp;
}

