// 5. محرك الاختبار (فصل الأسئلة، إعداد الـ Session والمؤقتات)
// ==========================================================================
function prepareQuizSession() {
    let pool = [];
    
    if (state.selectedMode === 'difficulty') {
        // تصفية الأسئلة حسب مستوى الصعوبة المحدد
        pool = QUESTIONS.filter(q => q.difficulty === state.selectedVal);
        // نحدد عدد الأسئلة المطلوب حسب الصعوبة
        let count = 10;
        if (state.selectedVal === 'medium') count = 15;
        if (state.selectedVal === 'hard') count = 20;
        if (state.selectedVal === 'expert') count = 25;
        
        // خلط واختيار العدد المطلق
        pool = shuffleArray(pool).slice(0, count);
    } else {
        // تصفية الأسئلة حسب التصنيف المحدد
        pool = QUESTIONS.filter(q => q.category === state.selectedVal);
        // نأخذ 10 أسئلة من هذا التصنيف
        pool = shuffleArray(pool).slice(0, 10);
    }
    
    if (pool.length === 0) {
        alert("عذراً، لم نجد أسئلة كافية تتطابق مع اختيارك.");
        return;
    }
    
    // إعداد حالة الاختبار
    state.quizQuestions = pool;
    state.currentQuestionIdx = 0;
    state.score = 0;
    state.correctAnswers = 0;
    state.wrongAnswers = 0;
    state.timeSpent = 0;
    state.answersLog = [];
    
    // ضبط مؤقت السؤال حسب الصعوبة الفردية للأسئلة
    updateQuestionTimerDuration();
    
    // بدء المؤقت الكلي للاختبار
    clearInterval(state.runTimerInterval);
    state.runTimerInterval = setInterval(() => {
        state.timeSpent++;
    }, 1000);
    
    // الانتقال لشاشة الاختبار وعرض أول سؤال
    navigateTo('screen-quiz');
    displayQuestion();
}

function updateQuestionTimerDuration() {
    const currentQ = state.quizQuestions[state.currentQuestionIdx];
    if (currentQ.difficulty === 'easy') state.totalQuestionTime = 20;
    else if (currentQ.difficulty === 'medium') state.totalQuestionTime = 20;
    else if (currentQ.difficulty === 'hard') state.totalQuestionTime = 15;
    else if (currentQ.difficulty === 'expert') state.totalQuestionTime = 12;
    else state.totalQuestionTime = 20;
}

// عرض السؤال الحالي في واجهة المستخدم
function displayQuestion() {
    state.hasAnswered = false;
    
    // إلغاء مؤقت السؤال السابق إن وجد
    clearInterval(state.questionTimerInterval);
    
    const currentQ = state.quizQuestions[state.currentQuestionIdx];
    updateQuestionTimerDuration();
    state.questionTimeLeft = state.totalQuestionTime;
    
    // تحديث بيانات رأس شاشة الاختبار
    document.getElementById('quiz-question-index').innerText = state.currentQuestionIdx + 1;
    document.getElementById('quiz-total-questions').innerText = state.quizQuestions.length;
    
    const progressPercent = ((state.currentQuestionIdx + 1) / state.quizQuestions.length) * 100;
    document.getElementById('quiz-progress-bar-fill').style.width = `${progressPercent}%`;
    
    document.getElementById('quiz-current-category').innerText = currentQ.category;
    document.getElementById('quiz-current-score').innerText = state.score;
    
    // صعوبة السؤال
    const diffBadge = document.getElementById('question-difficulty-badge');
    const diffNames = { "easy": "سهل", "medium": "متوسط", "hard": "صعب", "expert": "خبير جداً" };
    diffBadge.innerText = diffNames[currentQ.difficulty] || currentQ.difficulty;
    diffBadge.className = `q-difficulty-badge ${currentQ.difficulty}`;
    
    // نص السؤال
    document.getElementById('question-text').innerText = currentQ.question;
    
    // خيارات الإجابة
    const optionsContainer = document.getElementById('options-grid-container');
    optionsContainer.innerHTML = '';
    
    const optionLetters = ["أ", "ب", "ج", "د"];
    
    currentQ.choices.forEach((choice, idx) => {
        const optionCard = document.createElement('div');
        optionCard.classList.add('option-card');
        optionCard.innerHTML = `
            <span class="option-letter">${optionLetters[idx]}</span>
            <span class="option-text">${choice}</span>
        `;
        
        optionCard.addEventListener('click', () => {
            if (!state.hasAnswered) {
                handleAnswerSelection(idx, optionCard);
            }
        });
        
        optionsContainer.appendChild(optionCard);
    });
    
    // إخفاء لوحة التفسير العلمي وتمرير زر التالي للإغلاق
    document.getElementById('feedback-panel').classList.add('hidden');
    const nextBtn = document.getElementById('next-question-btn');
    nextBtn.classList.add('disabled');
    nextBtn.disabled = true;
    
    // إطلاق مؤقت التنازل الدائري
    startQuestionCountdown();
}

// إطلاق مؤقت التنازل البصري الدائري
function startQuestionCountdown() {
    const timerRing = document.getElementById('timer-ring-fill');
    const timerDigits = document.getElementById('timer-digits');
    const timerContainer = document.querySelector('.smart-timer-container');
    
    timerContainer.classList.remove('timer-warning');
    timerDigits.innerText = state.questionTimeLeft;
    
    // محيط الدائرة = 2 * PI * R = 2 * 3.14159 * 50 = 314.159
    const circumference = 314.159;
    timerRing.style.strokeDasharray = `${circumference}`;
    timerRing.style.strokeDashoffset = '0';
    
    state.questionTimerInterval = setInterval(() => {
        state.questionTimeLeft--;
        timerDigits.innerText = state.questionTimeLeft;
        
        // حساب الإزاحة الدائرية
        const offset = circumference - (state.questionTimeLeft / state.totalQuestionTime) * circumference;
        timerRing.style.strokeDashoffset = offset;
        
        // تأثير تحذيري في آخر 5 ثوانٍ
        if (state.questionTimeLeft <= 5) {
            timerContainer.classList.add('timer-warning');
        }
        
        // انتهاء الوقت
        if (state.questionTimeLeft <= 0) {
            clearInterval(state.questionTimerInterval);
            handleAnswerTimeout();
        }
    }, 1000);
}

// معالجة اختيار إجابة من قبل المستخدم
function handleAnswerSelection(selectedIdx, selectedCard) {
    state.hasAnswered = true;
    clearInterval(state.questionTimerInterval);
    
    const currentQ = state.quizQuestions[state.currentQuestionIdx];
    const correctIdx = currentQ.correct;
    const isCorrect = (selectedIdx === correctIdx);
    
    // تجميد باقي كروت الاختيارات
    const allOptionCards = document.querySelectorAll('.option-card');
    allOptionCards.forEach(card => card.classList.add('disabled'));
    
    // تسجيل اللوج للمراجعة
    state.answersLog.push({
        question: currentQ.question,
        category: currentQ.category,
        choices: currentQ.choices,
        selected: selectedIdx,
        correct: correctIdx,
        isCorrect: isCorrect
    });
    
    if (isCorrect) {
        selectedCard.classList.add('correct');
        state.correctAnswers++;
        
        // احتساب النقاط بناءً على الصعوبة
        let points = 10;
        if (currentQ.difficulty === 'medium') points = 15;
        if (currentQ.difficulty === 'hard') points = 20;
        if (currentQ.difficulty === 'expert') points = 25;
        state.score += points;
        
        // عرض التغذية الراجعة
        showFeedbackPanel(true, currentQ.explanation);
    } else {
        selectedCard.classList.add('incorrect');
        state.wrongAnswers++;
        
        // تظليل الإجابة الصحيحة
        allOptionCards[correctIdx].classList.add('correct');
        
        // عرض التغذية الراجعة
        showFeedbackPanel(false, currentQ.explanation);
    }
    
    enableNextButton();
}

// معالجة انتهاء الوقت التلقائي
function handleAnswerTimeout() {
    state.hasAnswered = true;
    state.wrongAnswers++;
    
    const currentQ = state.quizQuestions[state.currentQuestionIdx];
    const correctIdx = currentQ.correct;
    
    // تجميد كافة الأزرار وتلوين الصحيح بالكامل
    const allOptionCards = document.querySelectorAll('.option-card');
    allOptionCards.forEach(card => card.classList.add('disabled'));
    allOptionCards[correctIdx].classList.add('correct');
    
    // تسجيل اللوج
    state.answersLog.push({
        question: currentQ.question,
        category: currentQ.category,
        choices: currentQ.choices,
        selected: -1, // رمز لانتهاء الوقت دون اختيار
        correct: correctIdx,
        isCorrect: false
    });
    
    showFeedbackPanel(false, "انتهى الوقت المحدد للإجابة! " + currentQ.explanation, "انتهى الوقت!");
    enableNextButton();
}

